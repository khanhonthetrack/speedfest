"""Generate every SpeedFest sound into game/audio/generated/ (Ogg Vorbis).

usage: python3 tools/audio/gen_all.py [--only engines|sfx|weather|music] [--png DIR]
Then run tools/audio/build.sh (or tools/godot_import.sh + fix_loops.py) so Godot imports them.

Deterministic: fixed seeds everywhere, so re-running produces the same audio.
"""
from __future__ import annotations

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import gen_engines as E  # noqa: E402
import gen_sfx as X  # noqa: E402
import gen_weather as W  # noqa: E402
import synth as S  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "game", "audio", "generated")
LAYERS_GD = os.path.join(ROOT, "game", "audio", "engine_layers.gd")

# Vorbis quality per kind (keeps the web download small)
Q_ENGINE = 3
Q_SFX = 3
Q_MUSIC = 2


def gen_engines(png_dir: str | None) -> int:
	total = 0
	layers = {}
	for ci, car in enumerate(E.CARS):
		c = E.CARS[car]
		info = {"idle_rpm": c["idle_rpm"], "redline": c["redline"], "turbo": c["turbo"], "layers": {}}
		for li, layer in enumerate(["idle", "mid", "high", "off"]):
			x, rpm = E.render_layer(car, layer, 1000 + ci * 10 + li)
			name = f"eng_{car}_{layer}"
			total += _save(name, x, Q_ENGINE, png_dir)
			info["layers"][layer] = round(rpm, 2)
		layers[car] = info
	x, f0 = E.turbo_loop()
	total += _save("car_turbo", x, Q_ENGINE, png_dir)
	total += _save("car_nitro", E.nitro_loop(), Q_ENGINE, png_dir)
	total += _save("car_squeal", E.squeal_loop(), Q_ENGINE, png_dir)
	total += _save("car_wind", E.wind_loop(), Q_ENGINE, png_dir)
	_write_layers_gd(layers, f0)
	return total


def gen_sfx(png_dir: str | None) -> int:
	total = 0
	for name, fn in X.ALL.items():
		total += _save(name, fn(), Q_SFX, png_dir)
	return total


def gen_weather(png_dir: str | None) -> int:
	total = 0
	for name, fn in W.ALL.items():
		total += _save(name, fn(), Q_SFX, png_dir)
	return total


def gen_music(png_dir: str | None) -> int:
	import gen_trap as M   # dark-trap beats (session 4); gen_music.py held the old synthwave loops
	total = 0
	for name, fn in M.ALL.items():
		x = fn()
		total += _save(name, x, Q_MUSIC, png_dir)
	return total


def _save(name: str, x, q: float, png_dir: str | None) -> int:
	path = os.path.join(OUT, name + ".ogg")
	size = S.write_ogg(path, x, q)
	secs = x.shape[0] / S.SR
	print(f"{name:24s} {secs:7.2f}s {size / 1024:8.1f} KB")
	if png_dir:
		S.spectrogram_png(path, os.path.join(png_dir, name + ".png"))
	return size


def _write_layers_gd(layers: dict, turbo_f0: float) -> None:
	lines = [
		"## GENERATED by tools/audio/gen_all.py. Do not edit: re-run the generator.",
		"## Base rpm of every engine loop (pitch_scale = rpm / base) and per-car audio traits.",
		"",
		f"const TURBO_BASE_HZ := {turbo_f0:.1f}",
		"const CARS := {",
	]
	for car, info in layers.items():
		ls = ", ".join(f'"{k}": {v}' for k, v in info["layers"].items())
		lines.append(
			f'\t"{car}": {{"idle_rpm": {info["idle_rpm"]}, "redline": {info["redline"]}, '
			f'"turbo": {info["turbo"]}, "layers": {{{ls}}}}},'
		)
	lines.append("}")
	with open(LAYERS_GD, "w") as fh:
		fh.write("\n".join(lines) + "\n")


def main() -> None:
	ap = argparse.ArgumentParser()
	ap.add_argument("--only", choices=["engines", "sfx", "weather", "music"], default=None)
	ap.add_argument("--png", default=None, help="write spectrogram PNGs into this directory")
	a = ap.parse_args()
	os.makedirs(OUT, exist_ok=True)
	total = 0
	if a.only in (None, "engines"):
		total += gen_engines(a.png)
	if a.only in (None, "sfx"):
		total += gen_sfx(a.png)
	if a.only in (None, "weather"):
		total += gen_weather(a.png)
	if a.only in (None, "music"):
		total += gen_music(a.png)
	print(f"TOTAL {total / 1024:.1f} KB")


if __name__ == "__main__":
	main()
