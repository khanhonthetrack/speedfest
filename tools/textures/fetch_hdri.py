#!/usr/bin/env python3
"""Fetch SpeedFest's sky panoramas from Poly Haven (CC0 HDRIs) and convert them for the sky shader.

For every theme it downloads the 2K Radiance HDR, scales it so the bright clouds sit just below
white (the sun disk itself is drawn by the shader, so clipping it costs nothing), encodes sRGB and
writes 8-bit equirect panoramas:
  game/assets/sky/<theme>_sky.jpg      1024x512, every build incl. web
  game/assets/hd/sky/<theme>_sky.jpg   2048x1024, desktop only (the Web preset excludes assets/hd/*)
and the generated table game/tracks/scenery/sky_panoramas.gd (per theme: source id, the linear
scale to undo, and the direction of the panorama's brightest spot, i.e. the sun). The shader maps
directions as u = fract(atan(d.x, -d.z) / TAU + rotation), v = acos(d.y) / PI (v = 0 at the top),
the same convention this script uses for the sun direction.

usage: python3 tools/textures/fetch_hdri.py [theme ...]     (then tools/godot_import.sh)
needs: numpy, Pillow, ffmpeg/ffprobe (Radiance HDR decoder), network access to polyhaven.com
"""
import argparse
import hashlib
import json
import math
import os
import subprocess
import tempfile
import urllib.request

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "game", "assets", "sky")
OUT_HD = os.path.join(ROOT, "game", "assets", "hd", "sky")
TABLE = os.path.join(ROOT, "game", "tracks", "scenery", "sky_panoramas.gd")

# theme -> Poly Haven HDRI id (all CC0, "pure sky" = no ground in the shot)
SKIES = {
	"city": "kloppenheim_07_puresky",    # overcast night lit by town lights: the neon city's rain clouds
	"arena": "kloppenheim_02_puresky",   # clear moonlit night: the stadium sky
	"coast": "belfast_sunset_puresky",   # low sun under a cloud deck: dusk over the sea
}
WHITE_PERCENTILE = 99.7   # this luminance percentile maps to WHITE_LEVEL (keeps cloud detail)
WHITE_LEVEL = 0.92


def _get(url: str) -> bytes:
	req = urllib.request.Request(url, headers={"User-Agent": "speedfest-asset-fetch"})
	with urllib.request.urlopen(req, timeout=120) as r:
		return r.read()


def _decode_hdr(path: str) -> np.ndarray:
	probe = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
		"stream=width,height", "-of", "csv=p=0", path], capture_output=True, check=True, text=True)
	w, h = (int(x) for x in probe.stdout.strip().split(","))
	raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", path, "-f", "rawvideo", "-pix_fmt",
		"gbrpf32le", "-"], capture_output=True, check=True).stdout
	g, b, r = np.frombuffer(raw, dtype="<f4").reshape(3, h, w)
	return np.stack([r, g, b], axis=-1).astype(np.float64)


def _srgb(x: np.ndarray) -> np.ndarray:
	x = np.clip(x, 0.0, 1.0)
	return np.where(x <= 0.0031308, x * 12.92, 1.055 * np.power(x, 1.0 / 2.4) - 0.055)


def _dir_of(u: float, v: float) -> tuple:
	theta = u * 2.0 * math.pi
	phi = v * math.pi
	return (math.sin(theta) * math.sin(phi), math.cos(phi), -math.cos(theta) * math.sin(phi))


def fetch(theme: str, tmp: str) -> dict:
	sid = SKIES[theme]
	files = json.loads(_get(f"https://api.polyhaven.com/files/{sid}"))
	info = files["hdri"]["2k"]["hdr"]
	data = _get(info["url"])
	if hashlib.md5(data).hexdigest() != info["md5"]:
		raise RuntimeError(f"{sid}: md5 mismatch")
	src = os.path.join(tmp, f"{sid}_2k.hdr")
	with open(src, "wb") as f:
		f.write(data)
	hdr = _decode_hdr(src)
	lum = hdr @ np.array([0.2126, 0.7152, 0.0722])
	scale = WHITE_LEVEL / max(float(np.percentile(lum, WHITE_PERCENTILE)), 1e-6)
	# brightest spot (blurred so a single hot pixel can't win): the sun, moon or town glow
	h, w = lum.shape
	k = 9
	pad = np.pad(lum, ((k, k), (k, k)), mode="wrap")
	cs = pad.cumsum(0).cumsum(1)
	box = cs[2 * k:, 2 * k:] - cs[:-2 * k, 2 * k:] - cs[2 * k:, :-2 * k] + cs[:-2 * k, :-2 * k]
	py, px = np.unravel_index(int(np.argmax(box[:h, :w])), (h, w))
	u, v = (px + 0.5) / w, (py + 0.5) / h
	ldr = (_srgb(hdr * scale) * 255.0 + 0.5).astype(np.uint8)
	img = Image.fromarray(ldr, "RGB")
	os.makedirs(OUT_HD, exist_ok=True)
	os.makedirs(OUT, exist_ok=True)
	img.resize((2048, 1024), Image.LANCZOS).save(os.path.join(OUT_HD, f"{theme}_sky.jpg"), quality=92, subsampling=0)
	img.resize((1024, 512), Image.LANCZOS).save(os.path.join(OUT, f"{theme}_sky.jpg"), quality=92, subsampling=0)
	d = _dir_of(u, v)
	print(f"{theme:6s} {sid:28s} scale={scale:.3f} bright u={u:.4f} v={v:.4f} dir=({d[0]:.3f}, {d[1]:.3f}, {d[2]:.3f}) "
		f"p50={np.percentile(lum, 50):.4f} max={lum.max():.1f}")
	return {"id": sid, "scale": scale, "bright_u": u, "bright_v": v}


def write_table(rows: dict) -> None:
	lines = [
		"## GENERATED by tools/textures/fetch_hdri.py. Do not edit: re-run the script.",
		"## Sky panoramas (Poly Haven CC0 HDRIs, docs/ASSETS.md): res://assets/sky/<theme>_sky.jpg (1K, all",
		"## builds) and res://assets/hd/sky/<theme>_sky.jpg (2K, desktop). \"scale\" is the linear factor the",
		"## HDR was multiplied by before 8-bit encoding (divide it out); \"bright_u\"/\"bright_v\" locate the",
		"## brightest spot (the sun) in the shader's equirect convention (see env_sky.gdshader).",
		"",
		"const SKIES := {",
	]
	for theme, r in rows.items():
		lines.append(f"\t\"{theme}\": {{\"id\": \"{r['id']}\", \"scale\": {r['scale']:.5f}, \"bright_u\": {r['bright_u']:.5f}, \"bright_v\": {r['bright_v']:.5f}}},")
	lines.append("}")
	with open(TABLE, "w") as f:
		f.write("\n".join(lines) + "\n")


def main() -> None:
	ap = argparse.ArgumentParser()
	ap.add_argument("themes", nargs="*", default=list(SKIES))
	a = ap.parse_args()
	rows = {}
	if os.path.exists(TABLE):
		# keep the rows of themes not fetched this time
		txt = open(TABLE).read()
		for theme in SKIES:
			key = f"\t\"{theme}\": "
			for line in txt.splitlines():
				if line.startswith(key):
					rows[theme] = json.loads(line[len(key):].rstrip(","))
	with tempfile.TemporaryDirectory() as tmp:
		for theme in a.themes:
			rows[theme] = fetch(theme, tmp)
	write_table({t: rows[t] for t in SKIES if t in rows})


if __name__ == "__main__":
	main()
